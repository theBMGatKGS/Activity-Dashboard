#!/usr/bin/env python3
"""Box-side: convert notebook-log.md into Data/notebook-log.js for Activity Dashboard.

Usage: python3 tools/make_log_js.py [path/to/notebook-log.md] [path/to/notebook-log.js]
  defaults: <dashboard>/Data/notebook-log.md -> <dashboard>/Data/notebook-log.js

- Keeps ONLY lines starting with "- [log]" (leading whitespace allowed); every other line is dropped.
- Opens the .md read-only and never modifies, moves or rewrites it.
- Writes window.DASH_NOTEBOOK_LOG = {...}; atomically (tmp file + rename). Output is git-ignored.
- Refuses to write over the .md itself, or to an output that isn't a .js file.
- Line format (Notebook commit 2fdcdb3):
  - [log] YYYY-MM-DD HH:MM | 20m | Channel | Audience | Subject | Account | Person | note
  Validation happens in the dashboard (bad lines are listed there). Here, any line with '@' in the Person or note field is dropped and counted.
"""
import json, os, sys, tempfile, datetime, pathlib, re

DASH = pathlib.Path(__file__).resolve().parents[1]
LOG_RE = re.compile(r"^\s*- \[log\]", re.I)

def extract(text):
    keep, dropped_at = [], 0
    for raw in text.splitlines():
        if not LOG_RE.match(raw):
            continue
        line = raw.strip()
        parts = [p.strip() for p in line.split("|")]
        if any(ch in p for p in parts[6:] for ch in "@\uff20\ufe6b"):  # person or note ("@", full-width "＠", small "﹫")
            dropped_at += 1
            continue
        keep.append(line)
    return keep, dropped_at

def main(argv):
    src = pathlib.Path(argv[1]) if len(argv) > 1 else DASH / "Data" / "notebook-log.md"
    out = pathlib.Path(argv[2]) if len(argv) > 2 else DASH / "Data" / "notebook-log.js"
    if out.suffix != ".js" or out.resolve() == src.resolve():
        sys.exit(f"refusing to write {out}: output must be a .js file different from the source")
    if not src.exists():
        sys.exit(f"no notebook log at {src}")
    with open(src, "r", encoding="utf-8") as f:  # read-only
        text = f.read()
    lines, dropped = extract(text)
    payload = {"generated_at": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
               "source": src.name, "format": "2fdcdb3", "lines": lines}
    body = "/* Generated by tools/make_log_js.py from " + src.name + " - only '- [log]' lines. Do not edit. */\n" \
           "window.DASH_NOTEBOOK_LOG = " + json.dumps(payload, ensure_ascii=False, indent=1).replace("</", "<\\/") + ";\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".notebook-log.", suffix=".tmp", dir=str(out.parent))
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(body)
    os.replace(tmp, out)
    print(f"wrote {out}: {len(lines)} [log] line(s)" + (f", {dropped} dropped (person or note contains '@')" if dropped else ""))

if __name__ == "__main__":
    main(sys.argv)
